class Game {
  final String id;
  final String title;
  final String genre;
  final String status;
  final String imageUrl;
  final double rating;
  final String comment;

  Game({
    required this.id,
    required this.title,
    required this.genre,
    required this.status,
    required this.imageUrl,
    required this.rating,
    required this.comment,
  });
}
